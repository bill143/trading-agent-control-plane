const { chromium } = require('playwright');
const crypto = require('crypto');
// usage: node walkthrough.js <url> <spki-pin> <out-dir> [video]
const [,, url, pin, out, mode] = process.argv;
function b32(s){const a='ABCDEFGHIJKLMNOPQRSTUVWXYZ234567';let bits='';for(const c of s.replace(/=+$/,'').toUpperCase())bits+=a.indexOf(c).toString(2).padStart(5,'0');const bytes=[];for(let i=0;i+8<=bits.length;i+=8)bytes.push(parseInt(bits.slice(i,i+8),2));return Buffer.from(bytes);}
function totp(secret){const ctr=Math.floor(Date.now()/1000/30);const b=Buffer.alloc(8);b.writeBigUInt64BE(BigInt(ctr));const h=crypto.createHmac('sha1',b32(secret)).update(b).digest();const o=h[h.length-1]&15;return String(((h.readUInt32BE(o)&0x7fffffff)%1e6)).padStart(6,'0');}
